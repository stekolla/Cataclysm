#!/usr/bin/env python3
"""Generate the allowed semantic PR title types and scopes."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = [
    "feat",
    "fix",
    "docs",
    "style",
    "refactor",
    "perf",
    "test",
    "build",
    "ci",
    "chore",
    "revert",
]


def render_config(root):
    mod_ids = []
    for path in (root / "data/mods").glob("*/*modinfo.json*"):
        if path.suffix != ".json" or "bn" in path.relative_to(root).as_posix():
            continue
        entries = json.loads(path.read_text(encoding="utf-8"))
        for entry in entries:
            if (
                isinstance(entry, dict)
                and entry.get("type") == "MOD_INFO"
                and isinstance(entry.get("id"), str)
            ):
                mod_ids.append(entry["id"])
                break

    scopes = ["UI", "balance", "port", "lua"]
    scopes.extend(
        f"mods/{mod_id}"
        for mod_id in sorted(mod_ids, key=lambda s: s.encode("utf-16-be"))
    )
    scopes.append("mods")

    def yaml_list(values):
        return "".join(
            f"  - {value if re.fullmatch(r'[A-Za-z0-9_/-]+', value) else json.dumps(value)}\n"
            for value in values
        )

    return (
        "# This file is generated by `scripts/semantic.py`, do not edit manually.\n"
        "#\n"
        "# For more on configuration:\n"
        "# https://github.com/Ezard/semantic-prs?tab=readme-ov-file#configuration-options\n"
        "#\n"
        "# Validate the PR title, and ignore all commit messages\n"
        "enabled: true\n"
        "titleOnly: true\n"
        f"types:\n{yaml_list(TYPES)}"
        f"scopes:\n{yaml_list(scopes)}"
    )


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    (ROOT / ".github/semantic.yml").write_text(render_config(ROOT), encoding="utf-8")


if __name__ == "__main__":
    main()
